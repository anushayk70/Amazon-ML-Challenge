from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score
)

def evaluate(y_true,y_pred):

    print("Accuracy:",
          accuracy_score(y_true,y_pred))

    print("Precision:",
          precision_score(y_true,y_pred,
                          zero_division=0))

    print("Recall:",
          recall_score(y_true,y_pred,
                       zero_division=0))

    print("F1:",
          f1_score(y_true,y_pred,
                   zero_division=0))
